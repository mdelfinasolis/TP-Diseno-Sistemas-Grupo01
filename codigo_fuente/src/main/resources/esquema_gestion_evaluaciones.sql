-- =====================================================================
-- Esquema de la base gestion_evaluaciones (PostgreSQL 16)
-- Tablas de las entidades usadas por CU020, CU021, CU025, CU026 y CU028.
-- Se ejecuta al iniciar la aplicación (spring.sql.init.mode=always):
-- borra y recrea las tablas.
-- =====================================================================

DROP TABLE IF EXISTS respuesta_seleccionada CASCADE;
DROP TABLE IF EXISTS pregunta_cuestionario CASCADE;
DROP TABLE IF EXISTS resultado_factor CASCADE;
DROP TABLE IF EXISTS pregunta_item_ponderacion CASCADE;
DROP TABLE IF EXISTS resultado_competencia CASCADE;
DROP TABLE IF EXISTS cuestionario CASCADE;
DROP TABLE IF EXISTS evaluacion CASCADE;
DROP TABLE IF EXISTS candidato CASCADE;
DROP TABLE IF EXISTS pregunta CASCADE;
DROP TABLE IF EXISTS item_opcion CASCADE;
DROP TABLE IF EXISTS opcion_respuesta CASCADE;
DROP TABLE IF EXISTS puesto_competencia CASCADE;
DROP TABLE IF EXISTS factor CASCADE;
DROP TABLE IF EXISTS competencia CASCADE;
DROP TABLE IF EXISTS puesto CASCADE;
DROP TABLE IF EXISTS empresa CASCADE;

CREATE TABLE empresa (
    id_empresa  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE puesto (
    codigo_puesto VARCHAR(20)  PRIMARY KEY,
    nombre        VARCHAR(100) NOT NULL UNIQUE,
    descripcion   VARCHAR(500),
    eliminado     BOOLEAN      NOT NULL DEFAULT FALSE,
    id_empresa    INTEGER      NOT NULL REFERENCES empresa (id_empresa)
);

CREATE TABLE competencia (
    codigo_competencia VARCHAR(20)  PRIMARY KEY,
    nombre             VARCHAR(100) NOT NULL UNIQUE,
    descripcion        VARCHAR(500),
    tipo               VARCHAR(50),
    eliminada          BOOLEAN      NOT NULL DEFAULT FALSE
);

-- Relación "requiere" (Puesto - Competencia) con ponderación mínima
CREATE TABLE puesto_competencia (
    codigo_puesto      VARCHAR(20) NOT NULL REFERENCES puesto (codigo_puesto),
    codigo_competencia VARCHAR(20) NOT NULL REFERENCES competencia (codigo_competencia),
    ponderacion_minima INTEGER     NOT NULL CHECK (ponderacion_minima BETWEEN 0 AND 10),
    PRIMARY KEY (codigo_puesto, codigo_competencia)
);

CREATE TABLE factor (
    codigo_factor      VARCHAR(20)  PRIMARY KEY,
    nombre             VARCHAR(100) NOT NULL,
    descripcion        VARCHAR(500),
    nro_orden          INTEGER      NOT NULL,
    eliminado          BOOLEAN      NOT NULL DEFAULT FALSE,
    codigo_competencia VARCHAR(20)  NOT NULL REFERENCES competencia (codigo_competencia)
);

CREATE TABLE opcion_respuesta (
    nombre_opcion_respuesta VARCHAR(100) PRIMARY KEY,
    descripcion             VARCHAR(500),
    eliminada               BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE item_opcion (
    nombre_opcion_respuesta VARCHAR(100) NOT NULL REFERENCES opcion_respuesta (nombre_opcion_respuesta),
    orden                   INTEGER      NOT NULL,
    descripcion             VARCHAR(100) NOT NULL,
    PRIMARY KEY (nombre_opcion_respuesta, orden)
);

CREATE TABLE pregunta (
    codigo_pregunta         VARCHAR(20)  PRIMARY KEY,
    nombre                  VARCHAR(100) NOT NULL,
    enunciado               VARCHAR(500) NOT NULL,
    descripcion             VARCHAR(500),
    eliminada               BOOLEAN      NOT NULL DEFAULT FALSE,
    codigo_factor           VARCHAR(20)  NOT NULL REFERENCES factor (codigo_factor),
    nombre_opcion_respuesta VARCHAR(100) NOT NULL REFERENCES opcion_respuesta (nombre_opcion_respuesta)
);

CREATE TABLE candidato (
    nro_candidato    INTEGER      PRIMARY KEY,
    nombre           VARCHAR(100) NOT NULL,
    apellido         VARCHAR(100) NOT NULL,
    tipo_documento   VARCHAR(3)   NOT NULL,
    nro_documento    VARCHAR(20)  NOT NULL,
    fecha_nacimiento DATE,
    genero           VARCHAR(1),
    nacionalidad     VARCHAR(50),
    email            VARCHAR(100),
    escolaridad      VARCHAR(100),
    eliminado        BOOLEAN      NOT NULL DEFAULT FALSE,
    UNIQUE (tipo_documento, nro_documento)
);

CREATE TABLE evaluacion (
    id_evaluacion             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_creacion            DATE        NOT NULL,
    cant_preguntas_por_bloque INTEGER     NOT NULL,
    codigo_puesto             VARCHAR(20) NOT NULL REFERENCES puesto (codigo_puesto)
);

-- Cuestionario + atributos de DetalleCuestionario (clase de asociación)
CREATE TABLE cuestionario (
    clave            VARCHAR(20) PRIMARY KEY,
    tiempo_maximo    INTEGER     NOT NULL,
    id_evaluacion    INTEGER     NOT NULL REFERENCES evaluacion (id_evaluacion),
    nro_candidato    INTEGER     NOT NULL REFERENCES candidato (nro_candidato),
    fecha_inicio     TIMESTAMP,
    fecha_fin        TIMESTAMP,
    estado           VARCHAR(20) NOT NULL,
    cantidad_accesos INTEGER     NOT NULL DEFAULT 0,
    ultimo_ingreso   TIMESTAMP
);

-- Relación "obtiene_resultado_en" (Cuestionario - Competencia)
CREATE TABLE resultado_competencia (
    id_resultado_competencia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    total                    DOUBLE PRECISION NOT NULL,
    clave_cuestionario       VARCHAR(20)      NOT NULL REFERENCES cuestionario (clave),
    codigo_competencia       VARCHAR(20)      NOT NULL REFERENCES competencia (codigo_competencia),
    UNIQUE (clave_cuestionario, codigo_competencia)
);

-- Clase de asociación (Pregunta, ItemOpcion): ponderación de cada ítem para la pregunta
CREATE TABLE pregunta_item_ponderacion (
    id_pregunta_item_ponderacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_pregunta              VARCHAR(20)      NOT NULL REFERENCES pregunta (codigo_pregunta),
    nombre_opcion_respuesta      VARCHAR(100)     NOT NULL,
    orden_item                   INTEGER          NOT NULL,
    ponderacion                  DOUBLE PRECISION NOT NULL CHECK (ponderacion >= 0),
    FOREIGN KEY (nombre_opcion_respuesta, orden_item) REFERENCES item_opcion (nombre_opcion_respuesta, orden),
    UNIQUE (codigo_pregunta, nombre_opcion_respuesta, orden_item)
);

-- Relación "obtiene_resultado_en" (Cuestionario - Factor)
CREATE TABLE resultado_factor (
    id_resultado_factor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    total               DOUBLE PRECISION NOT NULL,
    clave_cuestionario  VARCHAR(20)      NOT NULL REFERENCES cuestionario (clave),
    codigo_factor       VARCHAR(20)      NOT NULL REFERENCES factor (codigo_factor),
    UNIQUE (clave_cuestionario, codigo_factor)
);

-- Preguntas asignadas al cuestionario, con su orden y bloque (paso del wizard)
CREATE TABLE pregunta_cuestionario (
    id_pregunta_cuestionario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave_cuestionario       VARCHAR(20) NOT NULL REFERENCES cuestionario (clave),
    codigo_pregunta          VARCHAR(20) NOT NULL REFERENCES pregunta (codigo_pregunta),
    orden                    INTEGER     NOT NULL,
    nro_bloque               INTEGER     NOT NULL,
    UNIQUE (clave_cuestionario, codigo_pregunta),
    UNIQUE (clave_cuestionario, orden)
);

-- Respuesta (0..1) de cada pregunta del cuestionario: ítem elegido
CREATE TABLE respuesta_seleccionada (
    id_respuesta_seleccionada INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pregunta_cuestionario  INTEGER      NOT NULL UNIQUE REFERENCES pregunta_cuestionario (id_pregunta_cuestionario),
    nombre_opcion_respuesta   VARCHAR(100) NOT NULL,
    orden_item                INTEGER      NOT NULL,
    fecha_respuesta           TIMESTAMP    NOT NULL,
    FOREIGN KEY (nombre_opcion_respuesta, orden_item) REFERENCES item_opcion (nombre_opcion_respuesta, orden)
);
